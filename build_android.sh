#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
cd "$ROOT"

if ! command -v flutter >/dev/null 2>&1; then
  echo "ERROR: Flutter SDK tidak ditemukan. Install Flutter dan Android SDK dahulu." >&2
  exit 1
fi

if [ ! -d android ]; then
  flutter create --platforms=android --project-name mototext_ble --org com.mototext .
fi

python3 - <<'PY'
from pathlib import Path
import re
manifest = Path('android/app/src/main/AndroidManifest.xml')
text = manifest.read_text(encoding='utf-8')
permissions = '''
    <uses-feature android:name="android.hardware.bluetooth_le" android:required="true" />
    <uses-permission android:name="android.permission.BLUETOOTH" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.BLUETOOTH_ADMIN" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.BLUETOOTH_SCAN" android:usesPermissionFlags="neverForLocation" />
    <uses-permission android:name="android.permission.BLUETOOTH_CONNECT" />
    <uses-permission android:name="android.permission.ACCESS_FINE_LOCATION" android:maxSdkVersion="30" />
    <uses-permission android:name="android.permission.POST_NOTIFICATIONS" />
    <uses-permission android:name="android.permission.VIBRATE" />
'''
missing = []
for line in permissions.splitlines():
    match = re.search(r'android:name="([^"]+)"', line)
    if match and match.group(1) not in text:
        missing.append(line)
if missing:
    text = re.sub(r'(<manifest\b[^>]*>)', lambda match: match.group(1) + '\n' + '\n'.join(missing) + '\n', text, count=1)
text = re.sub(r'android:label="[^"]+"', 'android:label="MotoAlert"', text, count=1)
manifest.write_text(text, encoding='utf-8')

# flutter_local_notifications 20+ needs Java API desugaring. Support both
# Gradle Kotlin DSL and the older Groovy DSL generated by Flutter.
for gradle_path in (Path('android/app/build.gradle.kts'), Path('android/app/build.gradle')):
    if not gradle_path.exists():
        continue
    gradle = gradle_path.read_text(encoding='utf-8')
    is_kts = gradle_path.suffix == '.kts'
    if is_kts:
        if 'isCoreLibraryDesugaringEnabled' not in gradle:
            gradle = re.sub(r'(compileOptions\s*\{)', r'\1\n        isCoreLibraryDesugaringEnabled = true', gradle, count=1)
        if 'multiDexEnabled' not in gradle:
            gradle = re.sub(r'(defaultConfig\s*\{)', r'\1\n        multiDexEnabled = true', gradle, count=1)
        if 'desugar_jdk_libs' not in gradle:
            gradle = re.sub(r'(dependencies\s*\{)', r'\1\n    coreLibraryDesugaring("com.android.tools:desugar_jdk_libs:2.1.4")', gradle, count=1)
    else:
        if 'coreLibraryDesugaringEnabled' not in gradle:
            gradle = re.sub(r'(compileOptions\s*\{)', r'\1\n        coreLibraryDesugaringEnabled true', gradle, count=1)
        if 'multiDexEnabled' not in gradle:
            gradle = re.sub(r'(defaultConfig\s*\{)', r'\1\n        multiDexEnabled true', gradle, count=1)
        if 'desugar_jdk_libs' not in gradle:
            gradle = re.sub(r'(dependencies\s*\{)', r"\1\n    coreLibraryDesugaring 'com.android.tools:desugar_jdk_libs:2.1.4'", gradle, count=1)
    gradle_path.write_text(gradle, encoding='utf-8')
PY

flutter pub get
dart format lib
flutter analyze
flutter test
flutter build apk --debug
printf '\nAPK berhasil dibuat di:\n%s\n' "$ROOT/build/app/outputs/flutter-apk/app-debug.apk"
